print(10 * 5) #50 Because 10 multiplied by 5 is 50
print(10 ** 2) #100 Because it would be 10 squared
print(15 / 10) #1.5 Because you are dividing 15 by 10 
print(15 // 10) #1 Because since there are two slashes, it's implying there won't be a decimal value, rather its rounded to the nearest whole number
print(-15 // 10) #-2 Because when you divide you get -1.5, which rounds down to the nearest whole number -2
print(15 % 10) #5 Because 15 divided by 10 is 1 with a remainder of 5
print(10 % 15) #10 Because 10 divided by 15 is 0 with a remainder of 10
print(10 % 10) #0 Because there is no remainder when 10 is divided by itself
print(0 % 10) #0 Because there is no remainder when 0 is divided by 10
print(10 / 15) #0.666 because 10 divided by 15 is 0.666. This is incorrect because the value is irrational.